const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const gzipPath = path.join(root, "templates", "rules.txt.gz");
const outputPath = path.join(root, "src", "rules-data.js");
const value = fs.readFileSync(gzipPath).toString("base64");
const output = `/* Generated by scripts/generate-rules-data.cjs. */\nexport const RULES_B64 =\n  ${JSON.stringify(value)};\n`;

if (
  !fs.existsSync(outputPath) ||
  fs.readFileSync(outputPath, "utf8") !== output
) {
  fs.writeFileSync(outputPath, output);
}
console.log(`rules-data.js: ${value.length} base64 chars`);
